"""
recorder.py — PipeWire Audio Capturer & Buffer Manager
=======================================================
Captures audio via sounddevice (PortAudio → PipeWire PulseAudio compat layer).

Architecture (VAD-segmented commit model):
  • Speech frames are accumulated in an utterance buffer
  • When silence >= utterance_silence_s, the utterance is committed (yielded)
  • Whisper transcribes the complete utterance → types only NEW text
  • No backspacing ever needed in the normal flow
  • force_commit_s prevents unbounded buffer growth during long speech
  • max_record_duration_s hard-caps session length to prevent RAM runaway

Mic lifecycle:
  Stream is created in start() and destroyed in stop() so the mic indicator
  only shows as active during an actual recording session.
"""

import asyncio
import logging
import os
import queue
import threading
import time
import tracemalloc
from pathlib import Path
from typing import AsyncGenerator

import numpy as np
import sounddevice as sd
from faster_whisper.vad import get_vad_model
from scipy.io import wavfile

logger = logging.getLogger(__name__)

_ZOLA_DEBUG = os.environ.get("ZOLA_DEBUG") == "1"

_VAD_WINDOW = 512        # Silero VAD frame size at 16 kHz
_VAD_SPEECH_PROB = 0.5   # speech probability above which a frame counts as speech
_VAD_CONTEXT_FRAMES = 5  # 100 ms mic blocks fed to the VAD per decision (0.5 s)


class AudioRecorder:
    def __init__(
        self,
        sample_rate: int = 16000,
        max_record_duration_s: float = 300.0,
    ) -> None:
        self.sample_rate = sample_rate
        self.channels = 1
        self.dtype = "float32"
        self._max_duration_s = max_record_duration_s

        self._queue: queue.Queue[np.ndarray] = queue.Queue()
        self._buffer: list[np.ndarray] = []
        self._buffer_lock = threading.Lock()

        self._is_recording = False
        self._session_start: float = 0.0
        self._stream: sd.InputStream | None = None

        # Declared here so stop() can safely check without AttributeError
        # even if start() was never called in debug mode.
        self._mem_snapshot_start = None

        # Per-session temp path — set by start(), used by stop()
        self._audio_path: Path | None = None

        # Silero VAD (bundled with faster-whisper) — decides speech vs silence
        self._vad = get_vad_model()

        logger.info(
            "AudioRecorder: ready (mic opens only during recording, "
            "rate=%dHz, max_duration=%.0fs)",
            sample_rate, max_record_duration_s,
        )

    # ----------------------------------------------------------------------- #
    # PortAudio callback — runs in C thread, must never block
    # ----------------------------------------------------------------------- #
    def _audio_callback(self, indata: np.ndarray, frames: int, time_info, status) -> None:
        if status:
            logger.warning("AudioRecorder callback: %s", status)
        if self._is_recording:
            self._queue.put_nowait(indata.copy())

    # ----------------------------------------------------------------------- #
    # Session control
    # ----------------------------------------------------------------------- #
    def start(self, audio_path: Path) -> None:
        """
        Open mic and begin recording.
        audio_path: secure per-session temp path generated by state.make_audio_tmp_path().
        """
        if self._is_recording:
            logger.warning("AudioRecorder.start(): already recording — ignored")
            return

        self._audio_path = audio_path

        # Drain stale queue
        while not self._queue.empty():
            try:
                self._queue.get_nowait()
            except queue.Empty:
                break

        with self._buffer_lock:
            self._buffer.clear()

        try:
            self._stream = sd.InputStream(
                samplerate=self.sample_rate,
                channels=self.channels,
                dtype=self.dtype,
                blocksize=int(self.sample_rate * 0.1),  # 100ms blocks
                callback=self._audio_callback,
            )
            self._stream.start()
        except Exception as exc:
            self._stream = None
            logger.exception("AudioRecorder: failed to open mic: %s", exc)
            raise

        self._is_recording = True
        self._session_start = time.monotonic()
        logger.info("AudioRecorder: mic opened — session started (path=%s)", audio_path)

        if _ZOLA_DEBUG:
            tracemalloc.start()
            self._mem_snapshot_start = tracemalloc.take_snapshot()
            logger.debug("[ZOLA_DEBUG] recorder: tracemalloc snapshot taken at session start")

    def request_stop(self) -> None:
        """Signal running generators to stop. Does NOT close mic; call stop() for that."""
        self._is_recording = False
        logger.debug("AudioRecorder: stop requested")

    def stop(self) -> tuple[Path, float]:
        """
        Stop and close mic stream; flush full session to WAV.
        Returns (audio_path, duration_s).
        The caller is responsible for deleting the temp file after use.
        """
        self._is_recording = False
        duration_s = max(time.monotonic() - self._session_start, 0.0)

        if self._stream is not None:
            try:
                if self._stream.active:
                    self._stream.stop()
                self._stream.close()
                logger.info("AudioRecorder: mic closed (%.1fs session)", duration_s)
            except Exception as exc:
                logger.error("AudioRecorder: stream close error: %s", exc)
            finally:
                self._stream = None

        # Short drain window for in-flight callback frames
        _end = time.monotonic() + 0.2
        while time.monotonic() < _end:
            try:
                chunk = self._queue.get_nowait()
                with self._buffer_lock:
                    self._buffer.append(chunk)
            except queue.Empty:
                break

        audio_path = self._audio_path
        if audio_path is None:
            # Fallback if start() was never called properly
            from state import make_audio_tmp_path
            audio_path = make_audio_tmp_path()

        with self._buffer_lock:
            if not self._buffer:
                # Normal for realtime sessions, which do not keep the session audio
                logger.debug("AudioRecorder.stop(): no audio — writing silence placeholder")
                _write_wav(audio_path, self.sample_rate,
                           np.zeros(self.sample_rate, dtype=np.float32))
                return audio_path, duration_s
            audio = np.concatenate(self._buffer, axis=0).flatten()

        _write_wav(audio_path, self.sample_rate, audio)
        logger.info(
            "AudioRecorder: %.1fs → %d samples → %s",
            duration_s, len(audio), audio_path,
        )

        if _ZOLA_DEBUG and self._mem_snapshot_start is not None:
            snapshot_end = tracemalloc.take_snapshot()
            diff = snapshot_end.compare_to(self._mem_snapshot_start, "lineno")
            logger.debug("[ZOLA_DEBUG] recorder: memory diff top-5 after stop():")
            for stat in diff[:5]:
                logger.debug("  %s", stat)
            tracemalloc.stop()

        return audio_path, duration_s

    def close(self) -> None:
        """Force-close on daemon shutdown."""
        self._is_recording = False
        if self._stream is not None:
            try:
                if self._stream.active:
                    self._stream.stop()
                self._stream.close()
            except Exception as exc:
                logger.error("AudioRecorder.close(): %s", exc)
            finally:
                self._stream = None

    def _is_speech(self, frames: list[np.ndarray]) -> bool:
        """True if the newest ~0.1 s of `frames` (recent mic blocks) contains speech."""
        audio = np.concatenate(frames).flatten()
        audio = audio[len(audio) % _VAD_WINDOW:]
        if len(audio) == 0:
            return False
        probs = self._vad(audio)
        return float(np.max(probs[-4:])) >= _VAD_SPEECH_PROB

    # ----------------------------------------------------------------------- #
    # Realtime: VAD-segmented utterance generator
    # ----------------------------------------------------------------------- #
    async def stream_utterances(
        self,
        utterance_silence_s: float = 0.7,
        force_commit_s: float = 10.0,
        chunk_s: float = 2.0,
        realtime_silence_timeout_s: float = 3.0,
        max_record_duration_s: float = 300.0,
    ) -> AsyncGenerator[np.ndarray, None]:
        """
        Async generator that yields complete utterance audio arrays.

        Yields each utterance when silence >= utterance_silence_s or
        force_commit_s is reached. Hard-stops at max_record_duration_s.

        Silence is measured in audio time (per mic block), not wall-clock time,
        so a slow transcription of the previous utterance cannot be mistaken
        for the user having stopped speaking.
        """
        utterance_buf: list[np.ndarray] = []
        utterance_samples = 0
        has_speech = False
        silence_s = 0.0
        recent: list[np.ndarray] = []

        vad_enabled = utterance_silence_s > 0.0
        limit_s = force_commit_s if vad_enabled else chunk_s
        force_samples = int(self.sample_rate * limit_s) if limit_s > 0 else None

        logger.info(
            "AudioRecorder: utterance stream started "
            "(vad=%.1fs, limit_s=%.1fs, timeout=%.1fs, max_dur=%.0fs)",
            utterance_silence_s if vad_enabled else 0.0,
            limit_s, realtime_silence_timeout_s, max_record_duration_s,
        )

        try:
            while True:
                # ── Hard cap: prevent runaway RAM accumulation ──
                elapsed = time.monotonic() - self._session_start
                if max_record_duration_s > 0 and elapsed >= max_record_duration_s:
                    logger.warning(
                        "AudioRecorder: max_record_duration_s (%.0fs) reached — auto-stopping",
                        max_record_duration_s,
                    )
                    self._is_recording = False
                    break

                try:
                    frame = self._queue.get_nowait()
                except queue.Empty:
                    # After a stop request, finish the frames already captured
                    if not self._is_recording:
                        break
                    await asyncio.sleep(0.05)
                    continue

                utterance_buf.append(frame)
                utterance_samples += len(frame)
                recent = (recent + [frame])[-_VAD_CONTEXT_FRAMES:]

                if self._is_speech(recent):
                    silence_s = 0.0
                    has_speech = True
                else:
                    silence_s += len(frame) / self.sample_rate

                # Auto-stop on long silence
                if realtime_silence_timeout_s > 0.0 and silence_s >= realtime_silence_timeout_s:
                    logger.info(
                        "AudioRecorder: realtime auto-stop — %.1fs silence",
                        realtime_silence_timeout_s,
                    )
                    self._is_recording = False
                    break

                # VAD: utterance boundary commit
                if vad_enabled and silence_s >= utterance_silence_s:
                    if has_speech:
                        utterance = np.concatenate(utterance_buf, axis=0).flatten()
                        logger.debug(
                            "Utterance committed via VAD (%.2fs)",
                            utterance_samples / self.sample_rate,
                        )
                        utterance_buf.clear()
                        utterance_samples = 0
                        has_speech = False
                        yield utterance
                    else:
                        # Nothing spoken yet: keep a short pre-roll so the next
                        # word onset is not clipped, drop the rest.
                        del utterance_buf[:-_VAD_CONTEXT_FRAMES]
                        utterance_samples = sum(len(f) for f in utterance_buf)
                    continue

                # Force-commit: max utterance duration
                if force_samples and utterance_samples >= force_samples:
                    cut = len(utterance_buf)
                    if vad_enabled:
                        # Cut at the quietest block of the last second, not mid-word
                        tail = utterance_buf[-10:]
                        quietest = min(
                            range(len(tail)), key=lambda i: float(np.mean(tail[i] ** 2))
                        )
                        cut = len(utterance_buf) - len(tail) + quietest + 1
                    utterance = np.concatenate(utterance_buf[:cut], axis=0).flatten()
                    logger.debug("Utterance committed via force-commit (%.1fs)", limit_s)
                    del utterance_buf[:cut]
                    utterance_samples = sum(len(f) for f in utterance_buf)
                    yield utterance

        except asyncio.CancelledError:
            logger.debug("AudioRecorder: stream_utterances cancelled")
            self._is_recording = False

        # Yield any remaining partial utterance
        if (utterance_buf and utterance_samples >= int(self.sample_rate * 0.3)
                and (has_speech or not vad_enabled)):
            yield np.concatenate(utterance_buf, axis=0).flatten()

        logger.debug("AudioRecorder: stream_utterances finished")

    # ----------------------------------------------------------------------- #
    # Batch: silence-triggered auto-stop monitor
    # ----------------------------------------------------------------------- #
    async def monitor_until_silence(
        self,
        silence_timeout_s: float = 3.0,
        min_record_s: float = 0.5,
        max_record_duration_s: float = 300.0,
    ) -> None:
        """
        For batch mode: monitors audio and sets _is_recording=False when
        silence_timeout_s of continuous silence is detected, or when
        max_record_duration_s is exceeded (RAM safety cap).
        """
        if silence_timeout_s <= 0:
            logger.info("AudioRecorder: silence monitor disabled (manual stop only)")
            while self._is_recording:
                await asyncio.sleep(0.1)
                # Hard cap even in manual-stop mode
                if max_record_duration_s > 0:
                    elapsed = time.monotonic() - self._session_start
                    if elapsed >= max_record_duration_s:
                        logger.warning(
                            "AudioRecorder: max_record_duration_s (%.0fs) reached — auto-stopping",
                            max_record_duration_s,
                        )
                        self._is_recording = False
                        break
                while True:
                    try:
                        chunk = self._queue.get_nowait()
                        with self._buffer_lock:
                            self._buffer.append(chunk.copy())
                    except queue.Empty:
                        break
            return

        silence_since: float | None = None
        session_start = time.monotonic()

        logger.info(
            "AudioRecorder: batch silence monitor armed "
            "(timeout=%.1fs, max_dur=%.0fs)",
            silence_timeout_s, max_record_duration_s,
        )

        try:
            while self._is_recording:
                await asyncio.sleep(0.1)

                # Hard cap
                elapsed = time.monotonic() - session_start
                if max_record_duration_s > 0 and elapsed >= max_record_duration_s:
                    logger.warning(
                        "AudioRecorder: max_record_duration_s (%.0fs) reached — auto-stopping",
                        max_record_duration_s,
                    )
                    self._is_recording = False
                    break

                chunks: list[np.ndarray] = []
                while True:
                    try:
                        chunk = self._queue.get_nowait()
                        with self._buffer_lock:
                            self._buffer.append(chunk.copy())
                        chunks.append(chunk)
                    except queue.Empty:
                        break

                if not chunks:
                    continue

                if (time.monotonic() - session_start) < min_record_s:
                    continue

                with self._buffer_lock:
                    recent_frames = self._buffer[-_VAD_CONTEXT_FRAMES:]

                if not self._is_speech(recent_frames):
                    if silence_since is None:
                        silence_since = time.monotonic()
                    elif (time.monotonic() - silence_since) >= silence_timeout_s:
                        logger.info(
                            "AudioRecorder: auto-stop — %.1fs silence",
                            silence_timeout_s,
                        )
                        self._is_recording = False
                        break
                else:
                    silence_since = None

        except asyncio.CancelledError:
            self._is_recording = False

        logger.debug("AudioRecorder: monitor_until_silence exited")


# --------------------------------------------------------------------------- #
# Private helper
# --------------------------------------------------------------------------- #
def _write_wav(path: Path, sample_rate: int, audio: np.ndarray) -> None:
    try:
        pcm16 = (np.clip(audio, -1.0, 1.0) * 32767).astype(np.int16)
        wavfile.write(str(path), sample_rate, pcm16)
        logger.debug("WAV: %s (%d samples @ %dHz)", path, len(pcm16), sample_rate)
    except Exception as exc:
        logger.exception("WAV write failed: %s", exc)
        raise
